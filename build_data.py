def main():
    os.makedirs(SVG_DIR, exist_ok=True)
    en = json.load(io.open(os.path.join(HERE, "codes_en.json"), encoding="utf-8")) \
        if os.path.exists(os.path.join(HERE, "codes_en.json")) else {}

    out, missing, failed = [], [], []
    for code, (ko, cont, tier) in sorted(COUNTRIES.items(),
                                         key=lambda x: (x[1][2], x[1][1], x[1][0])):
        if en and code not in en:
            missing.append(code)
            continue
        path = os.path.join(SVG_DIR, code + ".svg")
        if not os.path.exists(path) or os.path.getsize(path) < 100:
            r = subprocess.run(
                ["curl", "-s", "-m", "25", "-o", path,
                 "https://flagcdn.com/{0}.svg".format(code)])
            if r.returncode != 0 or not os.path.exists(path) \
                    or os.path.getsize(path) < 100:
                failed.append(code)
                continue
        out.append({"code": code, "ko": ko, "en": en.get(code, code.upper()),
                    "cont": cont, "tier": tier,
                    "svg": io.open(path, encoding="utf-8").read().strip()})

    tot = sum(len(x["svg"]) for x in out)
    print("수집 {0}개국 / SVG 합계 {1:.0f}KB (평균 {2:.0f}B)".format(
        len(out), tot / 1024, tot / max(1, len(out))))
    for t in (1, 2, 3):
        print("  tier{0}: {1}개".format(t, sum(1 for x in out if x["tier"] == t)))
    by_cont = {}
    for x in out:
        by_cont[x["cont"]] = by_cont.get(x["cont"], 0) + 1
    print("  대륙:", ", ".join("{0} {1}".format(k, v) for k, v in sorted(by_cont.items())))
    if missing:
        print("  [코드 없음]", missing)
    if failed:
        print("  [다운로드 실패]", failed)

    with io.open(os.path.join(HERE, "flags.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False)
    print("저장: flags.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
